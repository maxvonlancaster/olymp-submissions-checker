"""Extract corrected style features from the manifest-linked Parquet dataset."""

from __future__ import annotations

import csv
import math
from collections import Counter, defaultdict
from pathlib import Path

import pyarrow.parquet as parquet

from style_features import FEATURES, analyze_code_style, is_valid_source, normalized_code_sha256, validate_features

ROOT = Path(__file__).resolve().parent
DATASET = ROOT / "datasets" / "ai_code_detection.parquet"
MANIFEST = ROOT / "datasets" / "ai_code_detection_manifest.csv"
OUTPUT = ROOT / "datasets" / "ai_code_detection_features.csv"
REPORT = ROOT / "dataset_feature_extraction_report.md"
LANGUAGES = {"Python": ".py", "C++": ".cpp", "C": ".c", "C#": ".cs", "Pascal": ".pas"}
OUTPUT_FIELDS = (*FEATURES, "label", "split", "task_name", "source", "generator", "original_row_index")


def load_manifest(path: Path = MANIFEST):
    with path.open(encoding="utf-8", newline="") as handle:
        rows = list(csv.DictReader(handle))
    required = {"original_row_index", "task_name", "label", "source", "generator", "code_sha256", "split"}
    if not rows or set(rows[0]) != required:
        raise ValueError("Manifest has missing or unexpected columns")
    return rows


def extract_rows(manifest, parquet_rows):
    output, invalid, failures, seen = [], Counter(), [], set()
    for manifest_row in manifest:
        try:
            index = int(manifest_row["original_row_index"])
            if index in seen:
                raise ValueError("duplicate original_row_index")
            seen.add(index)
            if index < 0 or index >= len(parquet_rows):
                raise ValueError("original_row_index is outside Parquet bounds")
            source_row = parquet_rows[index]
            code = source_row.get("code")
            language = LANGUAGES.get(str(source_row.get("language_name", "")))
            if not isinstance(code, str) or not language:
                raise ValueError("missing code or unsupported language")
            if normalized_code_sha256(code) != manifest_row["code_sha256"]:
                raise ValueError("normalized-code SHA-256 mismatch")
            if not is_valid_source(code, language):
                invalid[language] += 1
            features = analyze_code_style(code, language)
            validate_features(features)
            output.append({**features, "label": manifest_row["label"], "split": manifest_row["split"], "task_name": manifest_row["task_name"], "source": manifest_row["source"], "generator": manifest_row["generator"], "original_row_index": index})
        except (KeyError, TypeError, ValueError, OverflowError) as error:
            failures.append(f"row {manifest_row.get('original_row_index', '<missing>')}: {error}")
    if len(output) != len(manifest) or len(seen) != len(manifest):
        failures.append(f"row cardinality mismatch: manifest={len(manifest)}, output={len(output)}")
    return output, invalid, failures


def write_output(rows, path: Path = OUTPUT):
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=OUTPUT_FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _distribution(rows):
    lines = ["| label | feature | count | mean | min | max |", "|---|---|---:|---:|---:|---:|"]
    grouped = defaultdict(list)
    for row in rows:
        for feature in FEATURES:
            grouped[(row["label"], feature)].append(float(row[feature]))
    for (label, feature), values in sorted(grouped.items()):
        lines.append(f"| {label} | {feature} | {len(values)} | {sum(values) / len(values):.6g} | {min(values):.6g} | {max(values):.6g} |")
    return "\n".join(lines)


def write_report(manifest, rows, invalid, failures, path: Path = REPORT):
    nonfinite = sum(not math.isfinite(float(row[feature])) for row in rows for feature in FEATURES)
    splits = Counter(row["split"] for row in rows)
    report = f"""# Dataset Feature Extraction Report

Generated by `extract_dataset_features.py` from the manifest-linked Parquet dataset.

## Validation

- Manifest rows: **{len(manifest):,}**
- Feature rows: **{len(rows):,}**
- Exactly one feature row per manifest row: **{'PASS' if len(rows) == len(manifest) and not failures else 'FAIL'}**
- Non-finite feature values written: **{nonfinite}**
- Failures: **{len(failures)}**
- Preserved split counts: **{', '.join(f'{key}={value:,}' for key, value in sorted(splits.items()))}**

## Invalid Code

- Invalid source count by language: **{', '.join(f'{key}={value:,}' for key, value in sorted(invalid.items())) or '0'}**
- Invalid source rows are retained only when the corrected extractor returns a validated conservative result; extraction failures are rejected.

## Feature Distributions by Class

{_distribution(rows)}

## Failures

{chr(10).join(f'- {failure}' for failure in failures) or '- None'}
"""
    path.write_text(report, encoding="utf-8")


def main():
    manifest = load_manifest()
    parquet_rows = parquet.read_table(DATASET).to_pylist()
    rows, invalid, failures = extract_rows(manifest, parquet_rows)
    if failures:
        raise RuntimeError("Extraction failed:\n" + "\n".join(failures[:20]))
    write_output(rows)
    write_report(manifest, rows, invalid, failures)
    print(f"Wrote {OUTPUT} ({len(rows)} rows)")
    print(f"Wrote {REPORT}")


if __name__ == "__main__":
    main()