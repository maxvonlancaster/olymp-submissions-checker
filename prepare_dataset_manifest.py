"""Create a leakage-controlled manifest from the committed Parquet dataset."""

from __future__ import annotations

import csv
import hashlib
from collections import Counter, defaultdict
from pathlib import Path

import pyarrow.parquet as parquet

from inspect_candidate_dataset import choose_group_split, normalize_code


ROOT = Path(__file__).resolve().parent
DATASET = ROOT / "datasets" / "ai_code_detection.parquet"
MANIFEST = ROOT / "datasets" / "ai_code_detection_manifest.csv"
REPORT = ROOT / "dataset_manifest_report.md"
SEED = 42
TEST_FRACTION = 0.20


def code_sha256(code: str) -> str:
    return hashlib.sha256(normalize_code(code).encode("utf-8")).hexdigest()


def clean_rows(rows: list[dict]) -> tuple[list[dict], Counter, dict[str, list[int]]]:
    groups: dict[str, list[int]] = defaultdict(list)
    for index, row in enumerate(rows):
        groups[code_sha256(row["code"])].append(index)

    excluded = Counter()
    kept = []
    duplicate_groups = {}
    for digest, indexes in groups.items():
        duplicate_groups[digest] = indexes
        labels = {rows[index]["label"] for index in indexes}
        if len(labels) > 1:
            excluded["cross_class_duplicate"] += len(indexes)
            continue
        canonical = min(indexes)
        kept.append({**rows[canonical], "original_row_index": canonical, "code_sha256": digest})
        excluded["same_class_duplicate"] += len(indexes) - 1
    kept.sort(key=lambda row: row["original_row_index"])
    return kept, excluded, duplicate_groups


def assign_splits(rows: list[dict], seed: int = SEED) -> tuple[list[dict], set[str], set[str]]:
    tasks: dict[str, list[int]] = defaultdict(list)
    for index, row in enumerate(rows):
        tasks[row["task_name"]].append(index)
    test_tasks, train_tasks = choose_group_split(rows, tasks)
    assigned = []
    for row in rows:
        split = "test" if row["task_name"] in test_tasks else "train"
        assigned.append({**row, "split": split})
    return assigned, train_tasks, test_tasks


def write_manifest(rows: list[dict], path: Path = MANIFEST) -> None:
    fields = ("original_row_index", "task_name", "label", "source", "generator", "code_sha256", "split")
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows({field: row[field] for field in fields} for row in rows)


def markdown_counts(counts: Counter) -> str:
    return ", ".join(f"{key}={value:,}" for key, value in sorted(counts.items()))


def make_report(raw_rows: list[dict], rows: list[dict], excluded: Counter, train_tasks: set[str], test_tasks: set[str], duplicate_groups: dict[str, list[int]]) -> None:
    before_labels = Counter(row["label"] for row in raw_rows)
    after_labels = Counter(row["label"] for row in rows)
    train = [row for row in rows if row["split"] == "train"]
    test = [row for row in rows if row["split"] == "test"]
    train_labels = Counter(row["label"] for row in train)
    test_labels = Counter(row["label"] for row in test)
    train_hashes = {row["code_sha256"] for row in train}
    test_hashes = {row["code_sha256"] for row in test}
    report = f"""# Dataset Manifest Report

Generated by `prepare_dataset_manifest.py` from the committed `datasets/ai_code_detection.parquet`. The Parquet file and notebook were not modified; no style features or models were used.

## Cleaning

- Rows before cleaning: **{len(raw_rows):,}** ({markdown_counts(before_labels)})
- Rows after cleaning: **{len(rows):,}** ({markdown_counts(after_labels)})
- Normalized duplicate groups before cleaning: **{sum(len(indexes) > 1 for indexes in duplicate_groups.values()):,}**
- Excluded records: **{sum(excluded.values()):,}** ({markdown_counts(excluded)})
- Same-class groups retain the lowest original row index as canonical.
- Every cross-class normalized-code group is excluded, including all copies.
- Remaining normalized-code duplicates across tasks: **0**; duplicate normalized code is therefore absent across split boundaries.

## Split

Seed **{SEED}**, approximately **{TEST_FRACTION:.0%}** test rows, with task groups intact.

| split | rows | tasks | Ai_generated | Human_written |
|---|---:|---:|---:|---:|
| train | {len(train):,} | {len(train_tasks):,} | {train_labels['Ai_generated']:,} | {train_labels['Human_written']:,} |
| test | {len(test):,} | {len(test_tasks):,} | {test_labels['Ai_generated']:,} | {test_labels['Human_written']:,} |

- Task overlap between train and test: **{len(train_tasks & test_tasks)}**
- Normalized-code overlap between train and test: **{len(train_hashes & test_hashes)}**
- Manifest columns: original row index, task name, label, source, generator, normalized code SHA-256, split.
"""
    REPORT.write_text(report, encoding="utf-8")


def main() -> None:
    table = parquet.read_table(DATASET)
    raw_rows = table.to_pylist()
    cleaned, excluded, duplicate_groups = clean_rows(raw_rows)
    assigned, train_tasks, test_tasks = assign_splits(cleaned)
    write_manifest(assigned)
    make_report(raw_rows, assigned, excluded, train_tasks, test_tasks, duplicate_groups)
    print(f"Wrote {MANIFEST}")
    print(f"Wrote {REPORT}")
    print(f"Rows: {len(raw_rows)} -> {len(assigned)}; excluded: {sum(excluded.values())}")
    print(f"Split: train={sum(row['split'] == 'train' for row in assigned)}, test={sum(row['split'] == 'test' for row in assigned)}")


if __name__ == "__main__":
    main()